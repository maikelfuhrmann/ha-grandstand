import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../custom_components/sports_hub/frontend/',import.meta.url);
const files=['model.js','style.js','panel.js'];
const version=JSON.parse(await readFile(new URL('../manifest.json',root),'utf8')).version;
let bundle=`// Sports Hub ${version} — generated by scripts/build.mjs; edit the source modules.\n`;
for(const file of files){
  let source=await readFile(new URL(file,root),'utf8');
  source=source.replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
  if(file==='panel.js')bundle+='const esc = escapeHtml;\n';
  bundle+=source+'\n';
}
await writeFile(new URL('sports-hub.js',root),bundle);
