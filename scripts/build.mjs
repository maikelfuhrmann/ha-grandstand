import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../custom_components/sports_hub/frontend/',import.meta.url);
const files=['model.js','i18n.js','dashboards.js','lineup-layout.js','f1-results-model.js','dossier-model.js','dossier-i18n.js','style.js','dossier-style.js','dossier.js','f1-dossier.js','f1-archive.js','match-i18n.js','f1-grid-card.js','match-center.js','match-style.js','radar.js','render.js','personal-model.js','personal-i18n.js','personal.js','panel.js'];
const version=JSON.parse(await readFile(new URL('../manifest.json',root),'utf8')).version;
let bundle=`// Grandstand ${version} — generated by scripts/build.mjs; edit the source modules.\n`;
for(const file of files){
  let source=await readFile(new URL(file,root),'utf8');
  source=source.replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
  if(file==='panel.js')bundle+='const esc = escapeHtml;\n';
  bundle+=source+'\n';
}
await writeFile(new URL('sports-hub.js',root),bundle);
